const languageData = {
  pl: { code: "PL", flag: "/images/flags/pl.svg", locale: "pl-PL" },
  nl: { code: "NL", flag: "/images/flags/be.svg", locale: "nl-BE" },
  fr: { code: "FR", flag: "/images/flags/fr.svg", locale: "fr-BE" }
};

const pageTitles = {
  pl: { home: "Strona główna", articles: "Artykuły", contact: "Kontakt" },
  nl: { home: "Startpagina", articles: "Artikels", contact: "Contact" },
  fr: { home: "Accueil", articles: "Articles", contact: "Contact" }
};
const originalDocumentTitle = document.title;

const originalContent = new Map();

function applyLanguage(language) {
  const selected = languageData[language] ? language : "pl";
  const dictionary = translations[selected];

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    if (!originalContent.has(element)) originalContent.set(element, element.textContent);
    element.textContent = dictionary[element.dataset.i18n] ?? originalContent.get(element);
  });
  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    if (!originalContent.has(element)) originalContent.set(element, element.innerHTML);
    element.innerHTML = dictionary[element.dataset.i18nHtml] ?? originalContent.get(element);
  });
  const articleBody = document.querySelector(".prose[data-i18n-html]");
  const translatedBody = document.querySelector(`template[data-article-translation="${selected}"]`);
  if (articleBody && translatedBody) articleBody.innerHTML = translatedBody.innerHTML;
  document.querySelectorAll("[data-translation-nl], [data-translation-fr]").forEach((element) => {
    if (!originalContent.has(element)) originalContent.set(element, element.textContent);
    const translated = element.getAttribute(`data-translation-${selected}`);
    element.textContent = selected === "pl" || !translated ? originalContent.get(element) : translated;
  });
  document.querySelectorAll("[data-category]").forEach((element) => {
    if (!originalContent.has(element)) originalContent.set(element, element.textContent);
    const original = originalContent.get(element);
    element.textContent = dictionary[`category.${original}`] ?? original;
  });
  document.querySelectorAll("time[datetime]").forEach((element) => {
    const date = new Date(element.getAttribute("datetime"));
    if (!Number.isNaN(date.valueOf())) {
      element.textContent = new Intl.DateTimeFormat(languageData[selected].locale, {
        day: "numeric", month: "long", year: "numeric"
      }).format(date);
    }
  });

  document.documentElement.lang = selected;
  const articleHeading = document.querySelector(".single-article__header h1");
  const pageTitle = articleHeading?.textContent || pageTitles[selected][document.body.dataset.page];
  if (selected === "pl") document.title = originalDocumentTitle;
  else if (pageTitle) document.title = `${pageTitle} | Polacy w Belgii`;
  document.querySelector(".language-picker__button img").src = languageData[selected].flag;
  document.querySelector(".language-picker__code").textContent = languageData[selected].code;
  document.querySelectorAll("[data-lang]").forEach((button) =>
    button.classList.toggle("is-active", button.dataset.lang === selected)
  );
  localStorage.setItem("siteLanguage", selected);
}

const toggle = document.querySelector(".nav-toggle");
const navigation = document.querySelector(".main-nav");
const languagePicker = document.querySelector(".language-picker");
const languageButton = document.querySelector(".language-picker__button");

if (toggle && navigation) {
  toggle.addEventListener("click", () => {
    const isOpen = toggle.getAttribute("aria-expanded") === "true";
    toggle.setAttribute("aria-expanded", String(!isOpen));
    navigation.classList.toggle("is-open", !isOpen);
    document.body.classList.toggle("menu-open", !isOpen);
  });
}

if (languagePicker && languageButton) {
  languageButton.addEventListener("click", () => {
    const isOpen = languageButton.getAttribute("aria-expanded") === "true";
    languageButton.setAttribute("aria-expanded", String(!isOpen));
    languagePicker.classList.toggle("is-open", !isOpen);
  });
  languagePicker.addEventListener("click", (event) => {
    const option = event.target.closest("[data-lang]");
    if (!option) return;
    applyLanguage(option.dataset.lang);
    languageButton.setAttribute("aria-expanded", "false");
    languagePicker.classList.remove("is-open");
  });
  document.addEventListener("click", (event) => {
    if (!languagePicker.contains(event.target)) {
      languageButton.setAttribute("aria-expanded", "false");
      languagePicker.classList.remove("is-open");
    }
  });
}

applyLanguage(localStorage.getItem("siteLanguage") || "pl");
